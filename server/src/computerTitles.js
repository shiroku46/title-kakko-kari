// shortcut: match themes to complete authored titles; arbitrary story-specific writing needs a language model.
function generateComputerTitles(synopsis, count) {
  if (!count) return [];
  const story = synopsis.replace(/『[^』]*』/gu, '').split(/(?<=[。!?！？])/u).filter(sentence =>
    !/メガホン|主演を|共演|らが出演/u.test(sentence)).join('');
  const scores = themes.map(({ pattern }) => new Set(story.match(pattern) || []).size);
  const best = Math.max(...scores);
  const candidates = best ? themes.flatMap(({ titles }, index) => scores[index] === best ? titles : []) : fallbackTitles;
  return shuffle([...new Set(candidates)]).slice(0, count);
}

